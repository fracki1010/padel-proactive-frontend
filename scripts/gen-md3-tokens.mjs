function buildRoles(mode) {
  const scheme = theme.schemes[mode];
  const roles = {};
  for (const role of SCHEME_ROLES) roles[role] = hexFromArgb(scheme[role]);
  for (const [role, tone] of Object.entries(NEUTRAL_TONES[mode])) {
    roles[role] = hexFromArgb(theme.palettes.neutral.tone(tone));
  }
  return roles;
}

