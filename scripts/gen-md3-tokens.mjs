console.log("✔ All critical contrast pairs pass.\n");

// ---------- write / check ----------

function sync(path, content, check) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (check) {
    if (current !== content) {
      console.error(`✖ Tokens are stale: ${path}`);
      console.error("  Run `npm run tokens` and commit the regenerated files.");
      return false;
    }
    console.log(`✔ ${path} is up to date`);
    return true;
  }
  writeFileSync(path, content);
  console.log(`✔ Wrote ${path}`);
  return true;
}

const check = process.argv.includes("--check");
const okTs = sync(TS_PATH, ts, check);
const okCss = sync(CSS_PATH, css, check);
if (!okTs || !okCss) process.exit(1);